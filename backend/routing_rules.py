_WORD_RE = re.compile(r"\s+")


def score_offices(text: str) -> list[tuple[str, int]]:
    """回傳 [(單位, 分數)]，分數由高到低；沒有任何關鍵字命中就回空清單。"""
    lowered = _WORD_RE.sub("", (text or "").lower())
    scores: dict[str, int] = {}
    for office, weight, words in RULES:
        for word in words:
            key = _WORD_RE.sub("", word.lower())
            if key and key in lowered:
                scores[office] = scores.get(office, 0) + weight * len(key)
    return sorted(scores.items(), key=lambda item: -item[1])


def normalize_office(text: str, offices: list[str]) -> str:
    """把模型輸出對回正式名稱；容忍「圖書資訊處 - 網路組」這種多空格寫法。"""
    plain = _WORD_RE.sub("", (text or "")).replace("－", "-").replace("—", "-")
    for office in sorted(offices, key=len, reverse=True):
        if _WORD_RE.sub("", office) in plain:
            return office
    return ""


def scope_lines(offices: list[str]) -> str:
    return "\n".join(f"- {office}：{SCOPES[office]}" for office in offices if office in SCOPES)
